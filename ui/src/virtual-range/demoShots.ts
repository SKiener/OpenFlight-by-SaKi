function demoShot(
  id: string,
  club: string,
  ballKmh: number,
  carryM: number,
  lateralM: number,
  points: PhysicsPoint[],
  rollPoints: PhysicsPoint[]
): RangeShot {
  const toScene = ([t, x, y, z]: PhysicsPoint): ScenePoint => ({ t, x: y, y: z, z: -x + 0 });
  const [, restX, restY] = rollPoints[rollPoints.length - 1];
  return {
    id,
    club,
    ballSpeedMph: ballKmh / KMH_PER_MPH,
    carryM,
    lateralM,
    flight: sampleFlight(points.map(toScene), 0.025),
    roll: rollPoints.map(toScene),
    totalM: Math.hypot(restX, restY),
  };
}

